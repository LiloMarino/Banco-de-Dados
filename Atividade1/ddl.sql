   execute immediate 'DROP TABLE compras CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE itens_carrinho CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE produtos CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE fabricante CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE subcategoria CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE categoria CASCADE CONSTRAINTS';
   execute immediate 'DROP TABLE cliente CASCADE CONSTRAINTS';
exception
   when others then
      null; -- Ignorar erros caso as tabelas não existam
end;
/

